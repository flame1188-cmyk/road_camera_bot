async def _do_llm_request(
    api_url: str,
    headers: dict,
    payload: dict,
    model_name: str,
    prompt_len: int,
    max_retries: int,
    client_getter,
) -> str:
    """
    Универсная функция выполнения HTTP-запроса к LLM API.
    Обрабатывает ретраи при 429, 5xx и таймаутах, парсит ответ.
    """
    # --- Sprint 5: Глобальный 429-cooldown (если был 429 ранее) ---
    waited_cooldown = await wait_429_cooldown()
    if waited_cooldown > 0:
        logger.info(
            f"LLM: после 429-cooldown ({waited_cooldown:.0f}s) — продолжаем запрос"
        )

    # --- Глобальный rate limiter ---
    global _last_llm_call_time
    now = time.monotonic()
    elapsed_since_last = now - _last_llm_call_time
    if elapsed_since_last < _MIN_LLM_INTERVAL and _last_llm_call_time > 0:
        cooldown = _MIN_LLM_INTERVAL - elapsed_since_last
        logger.info(f"Rate limiter: ждём {cooldown:.0f} сек между LLM-вызовами...")
        await asyncio.sleep(cooldown)

    # Диагностическое логирование: показываем реальную структуру messages
    # (включая history), а не только длину user_message.
    messages_in_payload = payload.get("messages", [])
    msgs_count = len(messages_in_payload)
    msgs_total_chars = sum(len(m.get("content", "")) for m in messages_in_payload)
    # Распределение по ролям
    roles_count = {}
    for m in messages_in_payload:
        r = m.get("role", "?")
        roles_count[r] = roles_count.get(r, 0) + 1
    roles_str = ", ".join(f"{r}={c}" for r, c in sorted(roles_count.items()))
    temperature = payload.get("temperature", "?")
    logger.info(
        f"LLM запрос: модель={model_name}, url={api_url}, "
        f"user_msg_len={prompt_len}, messages={msgs_count} ({roles_str}), "
        f"total_chars={msgs_total_chars}, temperature={temperature}"
    )

    # Разные стратегии ретраев для разных типов ошибок:
    # - 429 (Rate Limit): длинные ретраи [30, 60, 90, 120, 150] — провайдер просит подождать
    # - 5xx (Server Error): короткие ретраи [10, 30, 60] — серверу могло стать хуже,
    #   долго ждать бессмысленно. НЕ ретраим 5+ раз — это приводило к 7.5 мин ожидания
    #   и пользователь видел «Нейросеть анализирует...» 10 минут.
    # - 4xx (кроме 429): НЕ ретраим — это ошибки клиента (плохой промпт, слишком
    #   большой контекст, неверный API-ключ), повтор не поможет.
    # - Timeout: ретраим как 5xx — короткие задержки.
    retry_delays_429 = [30, 60, 90, 120, 150]
    retry_delays_5xx = [10, 30, 60]
    max_5xx_retries = min(3, max_retries)  # не более 3 ретраев для 5xx

    def _parse_error_body(resp) -> str:
        """Извлекает текст ошибки из тела ответа LLM API для диагностики."""
        try:
            body = resp.json()
            # ZhipuAI/OpenAI формат: {"error": {"message": "...", "code": "..."}}
            if isinstance(body, dict):
                err = body.get("error")
                if isinstance(err, dict):
                    msg = err.get("message", "")
                    code = err.get("code", "")
                    return f"{msg} (code={code})" if code else msg
                # Иногда просто строка
                if "message" in body:
                    return str(body["message"])
                # DeepSeek формат: {"error": {"message": "..."}}
                return str(body)[:300]
        except Exception:
            pass
        try:
            return resp.text[:300]
        except Exception:
            return ""

    for attempt in range(max_retries + 1):
        try:
            client = client_getter()
            response = await client.post(
                api_url,
                headers=headers,
                json=payload,
            )

            if response.status_code == 429:
                # Sprint 5: помечаем глобальный 429-cooldown, чтобы
                # другие coroutine (включая streaming-запросы) тоже ждали.
                retry_after_val: float | None = None
                if retry_after_raw := (
                    response.headers.get("Retry-After")
                    or response.headers.get("retry-after")
                ):
                    try:
                        retry_after_val = float(retry_after_raw)
                    except (ValueError, TypeError):
                        retry_after_val = None
                await mark_429(retry_after=retry_after_val)

                if attempt < max_retries:
                    retry_after = (
                        response.headers.get("Retry-After")
                        or response.headers.get("retry-after")
                    )
                    if not retry_after:
                        try:
                            body = response.json()
                            retry_after = str(body.get("retry_after") or body.get("wait") or "")
                        except Exception:
                            pass
                    if retry_after:
                        try:
                            wait = int(float(retry_after)) + 5
                        except (ValueError, TypeError):
                            wait = retry_delays_429[attempt]
                    else:
                        wait = retry_delays_429[attempt]

                    wait = max(wait, 30)

                    logger.warning(
                        f"LLM 429 Too Many Requests. "
                        f"Попытка {attempt + 1}/{max_retries}, "
                        f"ожидание {wait} сек..."
                        + (f" (Retry-After: {retry_after})" if retry_after else "")
                    )
                    await asyncio.sleep(wait)
                    continue
                else:
                    raise httpx.HTTPStatusError(
                        "Превышен лимит запросов к API. Подождите 5 минут и попробуйте снова.",
                        request=response.request,
                        response=response,
                    )

            # 4xx (кроме 429) — не ретраим: это ошибки клиента (плохой запрос,
            # слишком большой промпт, неверный ключ). Повтор не поможет.
            if 400 <= response.status_code < 500:
                err_body = _parse_error_body(response)
                # Спец-обработка типичных ошибок — даём пользователю понятное сообщение
                status = response.status_code
                hint = ""
                if status in (400, 413):
                    hint = (
                        " Вероятно, промпт превышает лимит контекста модели "
                        "(после добавления 7 новых кросс-таблиц размер промпта вырос). "
                        "Попробуйте платный провайдер или уменьшите период анализа."
                    )
                elif status in (401, 403):
                    hint = " Проверьте корректность API-ключа в .env (LLM_API_KEY)."
                logger.error(
                    f"LLM {status} ({response.reason_phrase}): {err_body}. "
                    f"Повтор не выполняется (4xx ошибка клиента)."
                )
                raise httpx.HTTPStatusError(
                    f"LLM API вернул {status}: {err_body or response.reason_phrase}.{hint}",
                    request=response.request,
                    response=response,
                )

            if response.status_code >= 500:
                err_body = _parse_error_body(response)
                if attempt < max_5xx_retries:
                    wait = retry_delays_5xx[min(attempt, len(retry_delays_5xx) - 1)]
                    logger.warning(
                        f"LLM {response.status_code} ({response.reason_phrase}): "
                        f"{err_body}. "
                        f"Попытка {attempt + 1}/{max_5xx_retries + 1} (5xx), "
                        f"ожидание {wait} сек..."
                    )
                    await asyncio.sleep(wait)
                    continue
                # Исчерпаны 5xx-ретраи — падаем с понятным сообщением
                logger.error(
                    f"LLM {response.status_code} после {max_5xx_retries + 1} попыток: "
                    f"{err_body}"
                )
                raise httpx.HTTPStatusError(
                    f"LLM API вернул {response.status_code} после "
                    f"{max_5xx_retries + 1} попыток: "
                    f"{err_body or response.reason_phrase}. "
                    f"Возможно, сервис временно недоступен или промпт слишком большой.",
                    request=response.request,
                    response=response,
                )

            response.raise_for_status()
            _last_llm_call_time = time.monotonic()
            break

        except httpx.HTTPStatusError:
            raise
        except httpx.TimeoutException:
            # Таймаут ретраим как 5xx — короткие задержки
            if attempt < max_5xx_retries:
                wait = retry_delays_5xx[min(attempt, len(retry_delays_5xx) - 1)]
                logger.warning(
                    f"LLM таймаут. "
                    f"Попытка {attempt + 1}/{max_5xx_retries + 1}, "
                    f"ожидание {wait} сек..."
                )
                await asyncio.sleep(wait)
                continue
            raise

    try:
        data = response.json()
    except json.JSONDecodeError as e:
        logger.error(f"LLM вернул невалидный JSON: {e}")
        raise ValueError(f"LLM вернул невалидный ответ") from e

    # Логирование структуры ответа
    if logger.isEnabledFor(logging.DEBUG):
        logger.debug(f"LLM полный ответ: {json.dumps(data, ensure_ascii=False)[:500]}")
    else:
        choices = data.get("choices") or [{}]
        choice = choices[0].get("message", {})
        content_preview = str(choice.get("content", ""))[:100]
        logger.info(
            f"LLM ответ структура: keys={list(data.keys())}, "
            f"finish_reason={choices[0].get('finish_reason')}, "
            f"content_type={type(choice.get('content')).__name__}, "
            f"content_preview={repr(content_preview)}"
        )

    if "choices" not in data or not data["choices"]:
        raise ValueError(f"Неожидаемый ответ API: {json.dumps(data, ensure_ascii=False)[:200]}")

    message = data["choices"][0]["message"]
    content = message.get("content", "") or ""

    # reasoning_content — формат GLM/ZhipuAI
    # reasoning — формат DeepSeek (AItunnel)
    reasoning = (message.get("reasoning_content", "") or "") or (message.get("reasoning", "") or "")
    reasoning_source = "reasoning_content" if message.get("reasoning_content") else ("reasoning" if message.get("reasoning") else "")

    # Если content пустой — пробуем извлечь ответ из reasoning/reasoning_content
    if not content and reasoning:
        logger.warning(
            f"LLM вернул пустой content, но есть {reasoning_source} ({len(reasoning)} симв.). "
            f"Пытаюсь извлечь ответ..."
        )
        paragraphs = [p.strip() for p in reasoning.split("\n") if p.strip()]
        if paragraphs:
            content = "\n".join(paragraphs[-5:]) if len(paragraphs) > 5 else "\n".join(paragraphs)
            logger.info(f"Извлечён ответ из {reasoning_source}: {len(content)} симв.")

    if not content:
        msg_keys = list(message.keys())
        logger.warning(
            f"LLM вернул пустой ответ. Ключи message: {msg_keys}, "
            f"finish_reason={data['choices'][0].get('finish_reason')}"
        )
        raise ValueError("LLM вернул пустой ответ (content='')")

    # Sprint 5: cost logging и для не-streaming режима.
    # Используем ту же функцию _log_llm_cost — она умеет работать с usage dict.
    usage_data = data.get("usage")
    model_for_log = LLM_MODEL  # не-streaming используется только для free-провайдера
    if usage_data:
        _log_llm_cost(
            model_name=model_for_log,
            usage=usage_data,
            chunks_emitted=1,  # не-streaming = один "чанк"
            total_chars=len(content),
        )
    else:
        logger.info(f"LLM ответ: {len(content)} символов, usage=N/A")

    return content


