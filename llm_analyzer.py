# ============================================================
# Sprint 5: LLM cost logging
# ============================================================
# Прайс-лист моделей (USD за 1M токенов). Источники:
#   - GLM-4-Flash: бесплатно (ZhipuAI промо), ставим $0 для cost-логов
#   - GLM-4.7-Flash: ~$0.07/1M input, $0.07/1M output (промо)
#   - DeepSeek (AItunnel): зависит от модели, по умолчанию $0.14/$0.28
# При изменении модели — обновить таблицу. При неизвестной модели —
# логируем usage без cost.
_LLM_PRICING_USD_PER_1M_TOKENS = {
    # ZhipuAI
    "glm-4-flash":         {"input": 0.0,   "output": 0.0},
    "glm-4.7-flash":       {"input": 0.07,  "output": 0.07},
    "glm-4-air":           {"input": 0.14,  "output": 0.14},
    "glm-4-plus":          {"input": 2.8,   "output": 2.8},
    # DeepSeek
    "deepseek-chat":       {"input": 0.14,  "output": 0.28},
    "deepseek-reasoner":   {"input": 0.55,  "output": 2.19},
}


def _log_llm_cost(
    model_name: str,
    usage: dict | None,
    chunks_emitted: int,
    total_chars: int,
) -> None:
    """
    Sprint 5: логирует cost LLM-запроса.

    Format: "LLM stream done: chunks=N, chars=M, prompt=P, completion=C, total=T, cost=$X.XXXX"

    Если usage отсутствует (провайдер не поддерживает stream_options) —
    логируем только chunks/chars, без cost.
    """
    if not usage:
        logger.info(
            f"LLM stream done: chunks={chunks_emitted}, chars={total_chars}, "
            f"usage=N/A (provider did not return usage)"
        )
        return

    prompt_tokens = usage.get("prompt_tokens", 0) or 0
    completion_tokens = usage.get("completion_tokens", 0) or 0
    total_tokens = usage.get("total_tokens", prompt_tokens + completion_tokens)

    pricing = _LLM_PRICING_USD_PER_1M_TOKENS.get(model_name.lower())
    if pricing:
        cost_usd = (
            prompt_tokens * pricing["input"] / 1_000_000
            + completion_tokens * pricing["output"] / 1_000_000
        )
        logger.info(
            f"LLM stream done: chunks={chunks_emitted}, chars={total_chars}, "
            f"prompt={prompt_tokens}, completion={completion_tokens}, "
            f"total={total_tokens}, model={model_name}, "
            f"cost=${cost_usd:.6f}"
        )
    else:
        # Модель не в таблице — логируем usage без cost
        logger.info(
            f"LLM stream done: chunks={chunks_emitted}, chars={total_chars}, "
            f"prompt={prompt_tokens}, completion={completion_tokens}, "
            f"total={total_tokens}, model={model_name}, "
            f"cost=N/A (model not in pricing table)"
        )


async def _do_llm_stream_request(
    api_url: str,
    headers: dict,
    payload: dict,
    model_name: str,
    prompt_len: int,
    client_getter,
) -> AsyncIterator[str]:
    """
    Универсальный streaming-вызов LLM API.
    Парсит SSE-ответ OpenAI-совместимого формата.

    Sprint 5: ДЕЛАЕТ retry на 429 — в отличие от предыдущей версии,
    которая сразу бросала httpx.HTTPStatusError. Логика:
      1. Перед запросом ждём 429-cooldown (если активен).
      2. Делаем запрос. Если 429 — mark_429() (cooldown 60 сек),
         ждём, повторяем (до _STREAM_429_MAX_RETRIES раз).
      3. На 200 — стримим чанки. Retry после начала стрима невозможен
         (commit к этому ответу).

    Если первый байт получен и потом поток оборвался — логируем и
    завершаемся (caller сохранит partial-результат).
    """
    # Sprint 5: retry-config для streaming 429.
    # Дольше, чем для sync — но streaming-вызовы дорогие (summary ~53 сек,
    # QA ~45 сек), и пользователь готов ждать, лишь бы получить ответ.
    _STREAM_429_RETRIES = 2  # итого до 3 попыток (1 + 2 retry)
    _STREAM_429_BASE_WAIT = 30.0  # первая пауза перед retry
    _STREAM_429_BACKOFF = 1.5  # множитель для последующих пауз

    # --- Sprint 5: Глобальный 429-cooldown (если был 429 ранее) ---
    waited_cooldown = await wait_429_cooldown()
    if waited_cooldown > 0:
        logger.info(
            f"LLM stream: после 429-cooldown ({waited_cooldown:.0f}s) "
            f"— продолжаем запрос"
        )

    # --- Глобальный rate limiter (один раз до запроса) ---
    global _last_llm_call_time
    now = time.monotonic()
    elapsed_since_last = now - _last_llm_call_time
    if elapsed_since_last < _MIN_LLM_INTERVAL and _last_llm_call_time > 0:
        cooldown = _MIN_LLM_INTERVAL - elapsed_since_last
        logger.info(f"Rate limiter (stream): ждём {cooldown:.0f} сек перед LLM-вызовом...")
        await asyncio.sleep(cooldown)

    msgs_count = len(payload.get("messages", []))
    logger.info(
        f"LLM stream запрос: модель={model_name}, url={api_url}, "
        f"user_msg_len={prompt_len}, messages={msgs_count}"
    )

    client = client_getter()
    # Sprint 5: retry-loop для 429. Важно — обернуть только фазу получения
    # HTTP-ответа (до aiter_lines). После получения 200 — уже не ретраим.
    attempt = 0
    while True:
        try:
            async with client.stream(
                "POST", api_url, headers=headers, json=payload,
            ) as response:
                # Проверяем статус ДО чтения потока.
                # 4xx/5xx — тело может содержать JSON с ошибкой, читаем его целиком.
                if response.status_code != 200:
                    body_text = ""
                    try:
                        async for chunk in response.aiter_bytes():
                            body_text += chunk.decode("utf-8", errors="replace")
                            if len(body_text) > 2000:
                                break
                    except Exception:
                        pass
                    _last_llm_call_time = time.monotonic()
                    err_preview = body_text[:300] if body_text else response.reason_phrase
                    logger.error(
                        f"LLM stream: HTTP {response.status_code} "
                        f"({response.reason_phrase}): {err_preview}"
                    )

                    # Sprint 5: если 429 — retry с backoff
                    if response.status_code == 429 and attempt < _STREAM_429_RETRIES:
                        # Парсим Retry-After (если есть)
                        retry_after_str = (
                            response.headers.get("Retry-After")
                            or response.headers.get("retry-after")
                        )
                        retry_after: float | None = None
                        if retry_after_str:
                            try:
                                retry_after = float(retry_after_str)
                            except (ValueError, TypeError):
                                retry_after = None
                        # Устанавливаем глобальный cooldown (60 сек)
                        await mark_429(retry_after=retry_after)
                        # Локальная пауза перед retry: используем max(retry_after, base_wait)
                        wait_sec = _STREAM_429_BASE_WAIT * (_STREAM_429_BACKOFF ** attempt)
                        if retry_after and retry_after > wait_sec:
                            wait_sec = retry_after
                        attempt += 1
                        logger.warning(
                            f"LLM stream: 429 Too Many Requests. "
                            f"Retry {attempt}/{_STREAM_429_RETRIES} через {wait_sec:.0f}с..."
                        )
                        await asyncio.sleep(wait_sec)
                        # На следующий retry — снова проверим cooldown
                        await wait_429_cooldown()
                        continue  # повторяем цикл

                    # Не 429 или retries закончились — бросаем ошибку
                    raise httpx.HTTPStatusError(
                        f"LLM stream API вернул {response.status_code}: {err_preview}",
                        request=response.request,
                        response=response,
                    )

                # 200 OK — стримим SSE-чанки
                _last_llm_call_time = time.monotonic()
                chunks_emitted = 0
                total_chars = 0
                # Sprint 5: usage из финального chunk'а (если stream_options.include_usage=true)
                usage_data: dict | None = None
                # Sprint 5.1: накапливаем reasoning_content для диагностики.
                # Локальная переменная — никаких race condition между параллельными вызовами.
                reasoning_accum: int = 0
                finish_reason: str | None = None

                async for line in response.aiter_lines():
                    # SSE-формат: строки вида "data: {...}" разделены пустой строкой.
                    # aiter_lines уже убирает \n, но пустые строки остаются как "".
                    if not line:
                        continue
                    if not line.startswith("data:"):
                        # Комментарий (":keep-alive") или что-то странное — игнорируем
                        continue
                    data_str = line[len("data:"):].strip()
                    if data_str == "[DONE]":
                        # Sprint 5: логируем cost перед выходом
                        _log_llm_cost(model_name, usage_data, chunks_emitted, total_chars)
                        # Sprint 5.1: детектируем reasoning-burnout (chunks=0, но
                        # были reasoning chunks). Логируем для последующей диагностики.
                        if chunks_emitted == 0 and reasoning_accum > 0:
                            logger.warning(
                                f"LLM stream: empty content but {reasoning_accum} симв. "
                                f"reasoning было сгенерировано (finish_reason={finish_reason}). "
                                f"Возможно, model упёрлась в max_tokens во время reasoning."
                            )
                        return
                    # Парсим JSON-чанк
                    try:
                        chunk_json = json.loads(data_str)
                    except json.JSONDecodeError as e:
                        logger.warning(
                            f"LLM stream: невалидный JSON chunk ({e}): "
                            f"{data_str[:120]}"
                        )
                        continue
                    # Sprint 5: ZhipuAI/OpenAI возвращает usage в финальном chunk'е
                    # (при stream_options.include_usage=true). choices при этом
                    # пустой [] или отсутствует — поэтому проверяем usage ПЕРЕД choices.
                    if chunk_json.get("usage"):
                        usage_data = chunk_json["usage"]
                    choices = chunk_json.get("choices") or []
                    if not choices:
                        continue
                    choice0 = choices[0]
                    delta = choice0.get("delta", {}) or {}
                    # Sprint 5.1: сохраняем finish_reason для диагностики burnout
                    if choice0.get("finish_reason"):
                        finish_reason = choice0["finish_reason"]
                    content_piece = delta.get("content") or ""
                    # Sprint 5.1: GLM-4.7-Flash в streaming mode отдаёт reasoning
                    # отдельно в delta.reasoning_content. Это «thinking» модель —
                    # при сложных вопросах reasoning может занять 8-12k токенов.
                    # Если content_piece пустой, но есть reasoning_content —
                    # НЕ стримим его (пользователю не нужен ход размышлений),
                    # но логируем для диагностики.
                    reasoning_piece = delta.get("reasoning_content") or ""
                    if reasoning_piece:
                        reasoning_accum += len(reasoning_piece)
                        # Логируем раз в ~4000 символов, чтобы не спамить.
                        if reasoning_accum % 4000 < len(reasoning_piece):
                            logger.info(
                                f"LLM stream: reasoning в процессе "
                                f"(накоплено ~{reasoning_accum} симв., "
                                f"content ещё не начался)"
                            )
                    if content_piece:
                        chunks_emitted += 1
                        total_chars += len(content_piece)
                        yield content_piece

                # Stream закончился без явного [DONE] (некоторые провайдеры так делают).
                # Sprint 5: всё равно логируем cost, если есть usage.
                _log_llm_cost(model_name, usage_data, chunks_emitted, total_chars)
                # Sprint 5.1: детектируем reasoning-burnout
                if chunks_emitted == 0 and reasoning_accum > 0:
                    logger.warning(
                        f"LLM stream: empty content (no [DONE]) but {reasoning_accum} симв. "
                        f"reasoning было сгенерировано. finish_reason={finish_reason}."
                    )
                # Успешно завершилось — выходим из retry-loop
                return

        except httpx.HTTPStatusError:
            # Если это 429 и мы попытались сделать retry — цикл уже продолжился.
            # Сюда попадаем только если retries закончились или это не 429.
            raise
        except httpx.TimeoutException as e:
            logger.error(f"LLM stream: timeout ({e})")
            raise
        except (asyncio.CancelledError, GeneratorExit):
            # Sprint 5: клиент отменил стрим (AbortController / http.disconnect).
            # httpx.AsyncClient.stream() через async with сам закроет соединение
            # при выходе из блока, но логируем для видимости.
            # chunks_emitted/total_chars могут быть не определены, если cancel
            # случился до входа в 200-OK ветку — используем .get() через locals().
            _locals = locals()
            logger.info(
                f"LLM stream: cancelled by consumer "
                f"(chunks={_locals.get('chunks_emitted', 0)}, "
                f"chars={_locals.get('total_chars', 0)})"
            )
            raise
        except Exception:
            # Обрыв соединения посреди потока — логируем и завершаем.
            # Если уже что-то yielded — caller сохранит partial. Если ничего —
            # caller увидит пустой результат.
            logger.exception("LLM stream: обрыв соединения посреди потока")
            return


async def get_ai_summary(
    comparison: dict[str, Any],
    reg_name: str,
    current_label: str,
    prev_label: str,
    raw_supplement: str = "",
    news_context: str = "",
    clusters_context: str = "",
    cross_tables_context: str = "",
    provider: LLMProvider = "free",
    current_cards: list[dict[str, Any]] | None = None,
    prev_cards: list[dict[str, Any]] | None = None,
    max_retries: int = 3,
) -> str:
    """
    Генерирует аналитическое резюме с помощью LLM.

    Для бесплатного метода (free): использует агрегированные метрики + кросс-таблицы.
    Для платного метода (paid): использует полные данные участников (Файл 2).

    Args:
        raw_supplement: Дополнительные данные из сырых карточек ДТП
        news_context: Новостной контекст из открытых источников
        clusters_context: Данные об очагах концентрации ДТП
        cross_tables_context: Кросс-таблицы для бесплатного метода
        provider: "free" (ZhipuAI/GLM) или "paid" (OpenAI-совместимый)
        current_cards: Сырые карточки текущего периода (для платного метода)
        prev_cards: Сырые карточки предыдущего периода (для платного метода)
        max_retries: Максимум ретраев для 429/5xx (по умолчанию 3 для summary —
            меньше ждать, чем для Q&A, т.к. пользователь смотрит на прогресс-бар).

    Returns:
        Текст резюме от нейросети
    """
    if provider == "paid" and current_cards is not None:
        # Платный метод: формируем полный набор данных
        logger.info(
            f"Платный метод: формирую полные данные для LLM "
            f"(текущий: {len(current_cards)} ДТП, "
            f"прошлый: {len(prev_cards) if prev_cards else 0} ДТП)"
        )

        current_full_data = format_full_data_as_csv(current_cards, current_label)
        # Предыдущий период — тоже полные данные для глубокого сравнения
        prev_full_data = ""
        if prev_cards:
            prev_full_data = format_full_data_as_csv(prev_cards, prev_label)
        logger.info(
            f"Платный метод: данные текущего = {len(current_full_data)} симв., "
            f"предыдущего = {len(prev_full_data)} символ."
        )

        prompt = build_paid_summary_prompt(
            comparison, reg_name, current_label, prev_label,
            current_full_data=current_full_data,
            prev_full_data=prev_full_data,
            news_context=news_context,
            clusters_context=clusters_context,
        )
        return await ask_llm(
            user_message=prompt, provider=provider, max_retries=max_retries,
        )
    else:
        # Бесплатный метод: агрегированные метрики + кросс-таблицы
        prompt = build_summary_prompt(
            comparison, reg_name, current_label, prev_label,
            raw_supplement=raw_supplement,
            news_context=news_context,
            clusters_context=clusters_context,
            cross_tables_context=cross_tables_context,
        )
        return await ask_llm(
            user_message=prompt, provider=provider, max_retries=max_retries,
        )


async def get_ai_answer(
    question: str,
    comparison: dict[str, Any],
    reg_name: str,
    current_label: str,
    prev_label: str,
    raw_supplement: str = "",
    news_context: str = "",
    clusters_context: str = "",
    cross_tables_context: str = "",
    provider: LLMProvider = "free",
    history: list[dict[str, str]] | None = None,
) -> str:
    """
    Отвечает на вопрос пользователя по данным с помощью LLM.

    Args:
        raw_supplement: Дополнительные данные из сырых карточек ДТП
        news_context: Новостной контекст из открытых источников
        clusters_context: Данные об очагах концентрации ДТП
        cross_tables_context: Кросс-таблицы для бесплатного метода
        provider: "free" (ZhipuAI/GLM) или "paid" (OpenAI-совместимый)
        history: История предыдущих пар Q&A в формате OpenAI
                 ([{role: "user"|"assistant", content: "..."}, ...]).
                 None или пустой список — режим без памяти (как раньше).

    Returns:
        Текст ответа от нейросети

    Sprint 6 hotfix2: реорганизована структура user_message.
    См. get_ai_answer_stream — там же логика.
    """
    # Шаг 1: собираем "контекст аналитики"
    metrics_text = format_metrics_for_prompt(
        comparison, reg_name, current_label, prev_label,
    )
    analytics_context = metrics_text
    if cross_tables_context:
        analytics_context += f"\n\n{cross_tables_context}"
    if clusters_context:
        analytics_context += f"\n\n{clusters_context}"
    if raw_supplement:
        analytics_context += f"\n\n{raw_supplement}"
    if news_context:
        analytics_context += f"\n\n{news_context}"

    # Шаг 2: финальный prompt
    if history:
        prompt = (
            f"{analytics_context}\n\n"
            f"=== КОНЕЦ КОНТЕКСТА АНАЛИТИКИ ===\n\n"
            f"[ПРОДОЛЖЕНИЕ ДИАЛОГА]\n"
            f"В предыдущих сообщениях этого диалога (role=user/assistant "
            f"в массиве messages) приведены предыдущие вопросы пользователя "
            f"и твои ответы. Учитывай их при ответе на текущий вопрос: "
            f"не противоречь, опирайся на уже сказанное, для follow-up "
            f"раскрывай новые аспекты.\n\n"
            f"ВАЖНО: текущий вопрос ниже — это НОВЫЙ вопрос пользователя. "
            f"Не путай его с продолжением последнего ответа. Если это "
            f"мета-вопрос про контекст диалога (например «ты помнишь "
            f"контекст?», «о чём мы говорили?») — кратко подтверди, "
            f"перечислив темы предыдущих вопросов (1-2 предложения), "
            f"и предложи продолжить. НЕ отвечай на последний вопрос "
            f"из истории заново.\n\n"
            f"=== НОВЫЙ ВОПРОС ПОЛЬЗОВАТЕЛЯ ===\n"
            f"{question}\n"
        )
    else:
        prompt = (
            f"{analytics_context}\n\n"
            f"=== КОНЕЦ КОНТЕКСТА АНАЛИТИКИ ===\n\n"
            f"=== ВОПРОС ПОЛЬЗОВАТЕЛЯ ===\n"
            f"{question}\n"
        )

    # Q&A — более низкая температура, чем для summary:
    # 0.3 = детерминированность, меньше расхождений на одних и тех же данных.
    return await ask_llm(
        user_message=prompt,
        provider=provider,
        history=history,
        temperature=0.3,
    )


# ============================================================
# Sprint 4: Streaming-обёртки для get_ai_summary / get_ai_answer
# ============================================================
# Те же prompt builders, но вызывают ask_llm_stream() вместо ask_llm().
# Возвращают AsyncIterator[str] — дельты контента по мере поступления.
# Caller (llm_ops) отвечает за:
#   - semaphore (acquire до вызова)
#   - сохранение результата в state/history
#   - кэширование (для summary)

async def get_ai_summary_stream(
    comparison: dict[str, Any],
    reg_name: str,
    current_label: str,
    prev_label: str,
    raw_supplement: str = "",
    news_context: str = "",
    clusters_context: str = "",
    cross_tables_context: str = "",
    provider: LLMProvider = "free",
    current_cards: list[dict[str, Any]] | None = None,
    prev_cards: list[dict[str, Any]] | None = None,
) -> AsyncIterator[str]:
    """
    Streaming-версия get_ai_summary: yields дельты резюме по мере
    поступления от LLM.

    Семантика идентична ask_llm_stream() — до первого yield может упасть
    с HTTPStatusError (429/5xx/4xx), после — partial при обрыве.
    """
    if provider == "paid" and current_cards is not None:
        logger.info(
            f"Платный метод (stream): формирую полные данные для LLM "
            f"(текущий: {len(current_cards)} ДТП, "
            f"прошлый: {len(prev_cards) if prev_cards else 0} ДТП)"
        )
        current_full_data = format_full_data_as_csv(current_cards, current_label)
        prev_full_data = ""
        if prev_cards:
            prev_full_data = format_full_data_as_csv(prev_cards, prev_label)
        logger.info(
            f"Платный метод (stream): данные текущего = {len(current_full_data)} симв., "
            f"предыдущего = {len(prev_full_data)} символ."
        )
        prompt = build_paid_summary_prompt(
            comparison, reg_name, current_label, prev_label,
            current_full_data=current_full_data,
            prev_full_data=prev_full_data,
            news_context=news_context,
            clusters_context=clusters_context,
        )
        async for delta in ask_llm_stream(
            user_message=prompt, provider=provider,
        ):
            yield delta
        return

    # Бесплатный метод
    prompt = build_summary_prompt(
        comparison, reg_name, current_label, prev_label,
        raw_supplement=raw_supplement,
        news_context=news_context,
        clusters_context=clusters_context,
        cross_tables_context=cross_tables_context,
    )
    async for delta in ask_llm_stream(
        user_message=prompt, provider=provider,
    ):
        yield delta


async def get_ai_answer_stream(
    question: str,
    comparison: dict[str, Any],
    reg_name: str,
    current_label: str,
    prev_label: str,
    raw_supplement: str = "",
    news_context: str = "",
    clusters_context: str = "",
    cross_tables_context: str = "",
    provider: LLMProvider = "free",
    history: list[dict[str, str]] | None = None,
) -> AsyncIterator[str]:
    """
    Streaming-версия get_ai_answer: yields дельты ответа по мере
    поступления от LLM. Используется для Q&A в реальном времени.

    Sprint 6 hotfix2: реорганизована структура user_message.
    Раньше маркер "[ПРОДОЛЖЕНИЕ ДИАЛОГА]" шёл в начале message, а
    40к символов аналитики (cross_tables) — в конце, что заставляло
    LLM путать новый вопрос с продолжением последнего Q&A из history.

    Теперь: аналитика в начале (как контекст), явный разделитель и
    новый вопрос — в самом конце. LLM чётко видит границу между
    контекстом и текущим вопросом.
    """
    # Шаг 1: собираем "контекст аналитики" — metrics + cross_tables + clusters
    metrics_text = format_metrics_for_prompt(
        comparison, reg_name, current_label, prev_label,
    )
    analytics_context = metrics_text
    if cross_tables_context:
        analytics_context += f"\n\n{cross_tables_context}"
    if clusters_context:
        analytics_context += f"\n\n{clusters_context}"
    if raw_supplement:
        analytics_context += f"\n\n{raw_supplement}"
    if news_context:
        analytics_context += f"\n\n{news_context}"

    # Шаг 2: финальный prompt — аналитика, потом явный marquer и вопрос
    if history:
        # Sprint 6 hotfix2: чёткая структура с вопросом в конце.
        # - Сначала контекст аналитики (LLM видит цифры)
        # - Потом явный marquer с инструкцией учитывать OpenAI history
        # - В самом конце — НОВЫЙ вопрос, чтобы LLM не спутала его
        #   с продолжением последнего Q&A из history
        prompt = (
            f"{analytics_context}\n\n"
            f"=== КОНЕЦ КОНТЕКСТА АНАЛИТИКИ ===\n\n"
            f"[ПРОДОЛЖЕНИЕ ДИАЛОГА]\n"
            f"В предыдущих сообщениях этого диалога (role=user/assistant "
            f"в массиве messages) приведены предыдущие вопросы пользователя "
            f"и твои ответы. Учитывай их при ответе на текущий вопрос: "
            f"не противоречь, опирайся на уже сказанное, для follow-up "
            f"раскрывай новые аспекты.\n\n"
            f"ВАЖНО: текущий вопрос ниже — это НОВЫЙ вопрос пользователя. "
            f"Не путай его с продолжением последнего ответа. Если это "
            f"мета-вопрос про контекст диалога (например «ты помнишь "
            f"контекст?», «о чём мы говорили?») — кратко подтверди, "
            f"перечислив темы предыдущих вопросов (1-2 предложения), "
            f"и предложи продолжить. НЕ отвечай на последний вопрос "
            f"из истории заново.\n\n"
            f"=== НОВЫЙ ВОПРОС ПОЛЬЗОВАТЕЛЯ ===\n"
            f"{question}\n"
        )
    else:
        # Без истории — простая структура (как раньше)
        prompt = (
            f"{analytics_context}\n\n"
            f"=== КОНЕЦ КОНТЕКСТА АНАЛИТИКИ ===\n\n"
            f"=== ВОПРОС ПОЛЬЗОВАТЕЛЯ ===\n"
            f"{question}\n"
        )

    async for delta in ask_llm_stream(
        user_message=prompt,
        provider=provider,
        history=history,
        temperature=0.3,
    ):
        yield delta

