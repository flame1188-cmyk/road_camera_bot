def format_statistical_metrics_for_prompt(stats: dict[str, Any]) -> str:
    """Форматирует производные статистические метрики (Этап 2) в текст для промпта LLM.

    Три блока:
      1. Severity rates — топ-5 самых «тяжёлых» разрезов по каждому срезу
         (погибших на 100 ДТП).
      2. Z-score аномалии — отклонения от среднего по числу ДТП и по тяжести.
      3. χ²-тесты — значимые связи между парами факторов.

    Пустые блоки (нет данных) пропускаются — в вывод попадают только
    содержательные результаты.
    """
    lines = ["СТАТИСТИЧЕСКИЕ МЕТРИКИ:"]
    lines.append("")

    # --- 1. Severity rates ---
    sr = stats.get("severity_rates", {})
    if sr:
        lines.append("ТЯЖЕСТЬ ПОСЛЕДСТВИЙ (погибших на 100 ДТП, топ-5 по каждому срезу):")
        lines.append("Используй эти данные, чтобы отвечать на вопросы про «самые опасные»")
        lines.append("районы/дороги/часы — там, где высокая тяжесть, а не просто много ДТП.")
        lines.append("")
        for slice_name, rows in sr.items():
            lines.append(f"  {slice_name}:")
            lines.append(
                f"    {'Категория':<32} | {'ДТП':>5} | {'Погибло':>7} | "
                f"{'Ранено':>6} | {'Пог./100':>8} | {'Ран./100':>8}"
            )
            for r in rows:
                key_str = r["key"] if len(r["key"]) <= 32 else r["key"][:29] + "..."
                lines.append(
                    f"    {key_str:<32} | {r['dtp']:>5} | {r['deaths']:>7} | "
                    f"{r['injured']:>6} | {r['deaths_per_100']:>8.1f} | "
                    f"{r['injured_per_100']:>8.1f}"
                )
            lines.append("")

    # --- 2. Z-score аномалии ---
    zan = stats.get("z_score_anomalies", {})
    if zan:
        lines.append("Z-SCORE АНОМАЛИИ (отклонения от среднего по региону):")
        lines.append("Положительный z_fatality = тяжесть выше среднего,")
        lines.append("отрицательный = ниже. |z|≥2 — статистически значимая аномалия.")
        lines.append("")
        for slice_name, rows in zan.items():
            lines.append(f"  {slice_name} (топ-5 по |z_fatality|):")
            lines.append(
                f"    {'Категория':<32} | {'ДТП':>5} | {'Пог./100':>8} | "
                f"{'z_дтп':>6} | {'z_тяж':>6} | {'Тяжесть':>20} | {'Частота':>20}"
            )
            for r in rows:
                key_str = r["key"] if len(r["key"]) <= 32 else r["key"][:29] + "..."
                lines.append(
                    f"    {key_str:<32} | {r['dtp']:>5} | {r['deaths_per_100']:>8.1f} | "
                    f"{r['z_dtp']:>+6.2f} | {r['z_fatality']:>+6.2f} | "
                    f"{r['label_fatality']:>20} | {r['label_dtp']:>20}"
                )
            lines.append("")

    # --- 3. χ²-тесты ---
    chi_tests = stats.get("chi_square_tests", [])
    if chi_tests:
        lines.append("ХИ-КВАДРАТ ТЕСТЫ НЕЗАВИСИМОСТИ (α=0.05):")
        lines.append("Если significant=True — между факторами есть статистически")
        lines.append("значимая связь (не случайная). Используй это для обоснования корреляций.")
        lines.append("")
        for t in chi_tests:
            sig_marker = "ЗНАЧИМО" if t.get("significant") else "не значимо"
            lines.append(
                f"  {t['test_name']}: χ²={t.get('chi2', 0)}, "
                f"df={t.get('df', 0)}, критерий={t.get('critical_005', '?')} "
                f"→ {sig_marker} ({t.get('note', '')})"
            )
        lines.append("")

    if not (sr or zan or chi_tests):
        lines.append("(недостаточно данных для статистического анализа)")
        lines.append("")

    return "\n".join(lines)


def format_metrics_for_prompt(
    comparison: dict[str, Any],
    reg_name: str,
    current_label: str,
    prev_label: str,
) -> str:
    """
    Форматирует результаты сравнения в текст для промпта LLM.
    """
    lines = []
    lines.append(f"Регион: {reg_name}")
    lines.append(f"Текущий период: {current_label}")
    lines.append(f"Предыдущий период: {prev_label}")
    lines.append("")

    # Основные показатели
    lines.append("ОСНОВНЫЕ ПОКАЗАТЕЛИ:")

    metrics_info = [
        ("Всего ДТП", comparison["total"]),
        ("Погибло, чел.", comparison["deaths"]),
        ("Ранено, чел.", comparison["injured"]),
        ("ДТП с нетрезвыми водителями", comparison["alcohol"]),
        ("ДТП с пешеходами", comparison["pedestrians"]),
        ("Погибло на 100 ДТП", comparison["deaths_per_100"]),
        ("Ранено на 100 ДТП", comparison["injured_per_100"]),
    ]

    for label, m in metrics_info:
        change = _format_change(m["change"])
        lines.append(
            f"- {label}: {_format_number(m['current'])} "
            f"(было {_format_number(m['previous'])}, изменение {change})"
        )

    lines.append("")

    # По дням недели
    lines.append("РАСПРЕДЕЛЕНИЕ ПО ДНЯМ НЕДЕЛИ:")
    cur_wd = comparison["by_weekday"]["current"]
    prev_wd = comparison["by_weekday"]["previous"]

    day_names = [
        "Понедельник", "Вторник", "Среда", "Четверг",
        "Пятница", "Суббота", "Воскресенье",
    ]

    for day_num in range(7):
        cur = cur_wd.get(day_num, 0)
        prv = prev_wd.get(day_num, 0)
        if prv > 0:
            change = round((cur - prv) / prv * 100, 1)
            lines.append(f"- {day_names[day_num]}: {cur} (было {prv}, {_format_change(change)})")
        else:
            lines.append(f"- {day_names[day_num]}: {cur}")

    lines.append("")

    # По часам
    lines.append("РАСПРЕДЕЛЕНИЕ ПО ЧАСАМ СУТОК (интервалы по 3 часа):")
    cur_hour = comparison["by_hour"]["current"]
    prev_hour = comparison["by_hour"]["previous"]

    for interval_start in range(0, 24, 3):
        interval_end = interval_start + 2
        interval_label = f"{interval_start:02d}:00-{interval_end:02d}:59"
        cur = sum(cur_hour.get(h, 0) for h in range(interval_start, interval_start + 3))
        prv = sum(prev_hour.get(h, 0) for h in range(interval_start, interval_start + 3))
        if prv > 0:
            change = round((cur - prv) / prv * 100, 1)
            lines.append(f"- {interval_label}: {cur} (было {prv}, {_format_change(change)})")
        else:
            lines.append(f"- {interval_label}: {cur}")

    lines.append("")

    # По видам ДТП
    lines.append("РАСПРЕДЕЛЕНИЕ ПО ВИДАМ ДТП:")
    cur_type = comparison["by_type"]["current"]
    prev_type = comparison["by_type"]["previous"]

    # Сортировка: по убыванию суммарной частоты, при равенстве — по имени (алфавит).
    # Без вторичного ключа порядок не детерминирован (PYTHONHASHSEED влияет на
    # итерацию set), что ломает golden-тесты и LLM-промпты между запусками.
    all_types = sorted(
        set(list(cur_type.keys()) + list(prev_type.keys())),
        key=lambda x: (-(cur_type.get(x, 0) + prev_type.get(x, 0)), x),
    )

    for tp_name in all_types[:10]:
        cur = cur_type.get(tp_name, 0)
        prv = prev_type.get(tp_name, 0)
        if prv > 0:
            change = round((cur - prv) / prv * 100, 1)
            lines.append(f"- {tp_name}: {cur} (было {prv}, {_format_change(change)})")
        else:
            lines.append(f"- {tp_name}: {cur}")

    lines.append("")

    # По погоде
    cur_weather = comparison["by_weather"]["current"]
    prev_weather = comparison["by_weather"]["previous"]

    if cur_weather or prev_weather:
        lines.append("РАСПРЕДЕЛЕНИЕ ПО ПОГОДНЫМ УСЛОВИЯМ:")
        # Та же детерминированная сортировка: по частоте, при равенстве — по имени.
        all_w = sorted(
            set(list(cur_weather.keys()) + list(prev_weather.keys())),
            key=lambda x: (-(cur_weather.get(x, 0) + prev_weather.get(x, 0)), x),
        )
        for w_name in all_w[:8]:
            cur = cur_weather.get(w_name, 0)
            prv = prev_weather.get(w_name, 0)
            if prv > 0:
                change = round((cur - prv) / prv * 100, 1)
                lines.append(f"- {w_name}: {cur} (было {prv}, {_format_change(change)})")
            else:
                lines.append(f"- {w_name}: {cur}")

    return "\n".join(lines)


